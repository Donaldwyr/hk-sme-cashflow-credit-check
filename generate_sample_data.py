# -*- coding: utf-8 -*-
"""
生成 sample_sme_fin.xlsx 模拟样例数据 (仅用于演示与自测, 非真实客户数据)。

表格结构 (Field Structure):
  Sheet "BS" 资产负债表 (Balance Sheet) / "IS" 利润表 (Income Statement)
  - 第 1 列: "项目" (科目名称)
  - 第 2 列起: 各会计期间列 (FY2021 / FY2022 / FY2023)
  - 金额单位: 千港元 (HKD'000)

用法: python generate_sample_data.py
生成文件: sample_sme_fin.xlsx
"""

import pandas as pd

OUTPUT = "sample_sme_fin.xlsx"

# 期间列
PERIODS = ["FY2021", "FY2022", "FY2023"]

# 资产负债表 (Balance Sheet), 单位: 千港元
# 勾稽关系: 资产总计 = 负债合计 + 所有者权益合计 (各期均平衡)
BS_ROWS = [
    # (项目, FY2021, FY2022, FY2023)
    ("货币资金", 4000, 3800, 3500),
    ("应收账款", 6500, 8200, 10500),
    ("存货", 6000, 7800, 10000),
    ("预付账款", 800, 1000, 1200),
    ("流动资产合计", 17300, 20800, 25200),
    ("固定资产净值", 7500, 8600, 9400),
    ("长期投资", 1000, 1000, 1000),
    ("非流动资产合计", 8500, 9600, 10400),
    ("资产总计", 25800, 30400, 35600),
    ("短期借款", 4500, 6000, 8000),
    ("应付账款", 3800, 4500, 5200),
    ("预收账款", 1200, 1300, 1400),
    ("其他流动负债", 1000, 1100, 1200),
    ("流动负债合计", 10500, 12900, 15800),
    ("长期借款", 4800, 5300, 6500),
    ("非流动负债合计", 4800, 5300, 6500),
    ("负债合计", 15300, 18200, 22300),
    ("实收资本", 5000, 5000, 5000),
    ("未分配利润", 5500, 7200, 8300),
    ("所有者权益合计", 10500, 12200, 13300),
    ("负债及所有者权益总计", 25800, 30400, 35600),
]

# 利润表 (Income Statement), 单位: 千港元
# 说明: "折旧与摊销"为披露的备忘科目(已含在营业成本/费用中), 用于现金流测算。
# 勾稽: 毛利 = 营业收入 - 营业成本; 税前利润 = 毛利 - 销售及管理费用 - 利息费用;
#       净利润 = 税前利润 - 所得税 (所得税按 16.5% 港利得税估算)。
IS_ROWS = [
    # (项目, FY2021, FY2022, FY2023)
    ("营业收入", 32000, 38000, 45000),
    ("营业成本", 22400, 26600, 31500),
    ("毛利", 9600, 11400, 13500),
    ("销售及管理费用", 4200, 5000, 5900),
    ("利息费用", 700, 850, 1050),
    ("折旧与摊销", 1100, 1300, 1500),
    ("税前利润", 4700, 5550, 6550),
    ("所得税", 776, 916, 1081),
    ("净利润", 3924, 4634, 5469),
]


def to_dataframe(rows):
    return pd.DataFrame(rows, columns=["项目"] + PERIODS)


def main():
    bs = to_dataframe(BS_ROWS)
    is_ = to_dataframe(IS_ROWS)
    with pd.ExcelWriter(OUTPUT, engine="openpyxl") as writer:
        bs.to_excel(writer, sheet_name="BS", index=False)
        is_.to_excel(writer, sheet_name="IS", index=False)
    print(f"已生成 {OUTPUT}")
    print(f"  BS 资产负债表: {bs.shape[0]} 行 x {bs.shape[1]} 列")
    print(f"  IS 利润表:     {is_.shape[0]} 行 x {is_.shape[1]} 列")


if __name__ == "__main__":
    main()
